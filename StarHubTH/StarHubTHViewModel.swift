    // MARK: - Installed mod registry (version + install date)

    /// Persistent record of when each mod was last installed/updated, keyed by
    /// folder name. Unlike the on-disk folder mtime (which `copyItem` preserves
    /// from the archive's packaging date and is therefore unreliable), this
    /// registry stores the *actual* installation timestamp on this machine.
    /// The update checker uses it for same-version detection: a Nexus upload
    /// newer than the registry date means the installed copy is stale.
    struct InstalledModRecord: Codable {
        let version: String
        let installedAt: Date
        /// The Nexus version known at install time, for mods whose manifest
        /// Version is stale (the author forgot to bump). When set and newer
        /// than the manifest version, the update checker uses this instead of
        /// the manifest's — so the mod is not permanently re-flagged. We never
        /// modify the user's manifest.json.
        var nexusVersion: String? = nil
    }

    // Registry keys are centralized in `UDKey` (shared with `ModFolderRepairer`
    // and any other module that needs to read/write the install registry).
    private static let installedModRegistryKey = UDKey.installedModRegistry
    /// Mirror of the primary registry, written on every save. Used to recover
    /// automatically when the primary blob is corrupt or missing.
    private static let installedModRegistryBackupKey = UDKey.installedModRegistryBackup

    /// In-memory mirror of the persisted registry. Without this cache, every
    /// single-mod lookup (`installedModNexusVersion`, `installedModDate`) would
    /// re-decode the full ~100KB JSON blob from UserDefaults — and since
    /// `effectiveVersion` calls `installedModNexusVersion` once per mod during
    /// every scan, that's 100+ full decodes per scan. The cache is populated
    /// lazily on first access, refreshed on every save, and guarded by
    /// `installedModRegistryLock` because reads happen on the background scan
    /// thread while writes (recordInstalledModNexusVersion) can happen on main.
    private var installedModRegistryCache: [String: InstalledModRecord]?
    private let installedModRegistryLock = NSLock()

    /// Loads the install registry from UserDefaults with automatic fallback:
    ///
    /// 1. **Primary key** — decode it. If valid, return it.
    /// 2. **Backup key** — if the primary is absent or corrupt, try the
    ///    backup. On success, promote the backup back to the primary key and
    ///    log a recovery notice.
    /// 3. **Neither is usable** — return `[:]`. The registry will be fully
    ///    rebuilt from disk by `syncInstalledModRegistry` on the next scan.
    ///
    /// Corrupt blobs (primary and/or backup) are purged so they don't block
    /// future saves.
    /// Returns the registry, populating the in-memory cache on first access.
    /// Subsequent calls read from the cache (no JSON decode, no UserDefaults
    /// I/O) — the cache is refreshed by `saveInstalledModRegistry` on writes.
    /// Thread-safe via `installedModRegistryLock`.
    private func loadInstalledModRegistry() -> [String: InstalledModRecord] {
        installedModRegistryLock.lock()
        defer { installedModRegistryLock.unlock() }
        if let cached = installedModRegistryCache {
            return cached
        }
        // Cold path: decode from UserDefaults (with backup fallback) exactly
        // once per session, then memoize.
        let loaded = Self.loadInstalledModRegistryFromDisk()
        installedModRegistryCache = loaded
        return loaded
    }

    /// Disk-level load with the primary/backup fallback chain. Static so it
    /// can run before the cache exists (called by `loadInstalledModRegistry`
    /// on the cold path, and by `clearInstalledModRegistryForTests` if a
    /// future test needs a disk-fresh copy).
    private static func loadInstalledModRegistryFromDisk() -> [String: InstalledModRecord] {
        let defaults = UserDefaults.standard

        // 1. Try the primary.
        if let primary = defaults.data(forKey: installedModRegistryKey),
           let decoded = try? JSONDecoder().decode([String: InstalledModRecord].self, from: primary) {
            return decoded
        }

        // Primary is absent or corrupt — purge it.
        if defaults.data(forKey: installedModRegistryKey) != nil {
            defaults.removeObject(forKey: installedModRegistryKey)
        }

        // 2. Try the backup.
        if let backup = defaults.data(forKey: installedModRegistryBackupKey),
           let decoded = try? JSONDecoder().decode([String: InstalledModRecord].self, from: backup) {
            // Promote the backup to the primary slot so subsequent loads are
            // fast and the (corrupt) primary is replaced.
            if let data = try? JSONEncoder().encode(decoded) {
                defaults.set(data, forKey: installedModRegistryKey)
            }
            NSLog("[StarHubFR] Install registry restored from backup (%d entries).",
                  decoded.count)
            return decoded
        }

        // Backup is also absent or corrupt — purge it too.
        if defaults.data(forKey: installedModRegistryBackupKey) != nil {
            defaults.removeObject(forKey: installedModRegistryBackupKey)
            NSLog("[StarHubFR] Install registry and backup both corrupt/unavailable — rebuilding from disk.")
        }

        // 3. Neither usable — empty; will be rebuilt on next scan.
        return [:]
    }

    /// Saves the registry to BOTH the primary and backup keys atomically. The
    /// backup guarantees that a corruption of one blob (e.g. a crashed write)
    /// can be recovered from the other on the next load.
    /// Updates the in-memory cache AND persists to BOTH the primary and backup
    /// keys. The `data` blob is encoded exactly once and reused for both keys
    /// (was encoded twice before). Thread-safe via `installedModRegistryLock`.
    private func saveInstalledModRegistry(_ map: [String: InstalledModRecord]) {
        guard let data = try? JSONEncoder().encode(map) else { return }
        installedModRegistryLock.lock()
        installedModRegistryCache = map
        installedModRegistryLock.unlock()
        let defaults = UserDefaults.standard
        defaults.set(data, forKey: Self.installedModRegistryKey)
        defaults.set(data, forKey: Self.installedModRegistryBackupKey)
    }

    /// Returns the recorded install date for a mod folder, or nil if the mod
    /// was never registered (e.g. installed before this feature existed).
    func installedModDate(for folderName: String) -> Date? {
        loadInstalledModRegistry()[folderName]?.installedAt
    }

    /// Returns the recorded Nexus version for a mod folder (the version the
    /// checker flagged on when the mod was last installed/updated from Nexus),
    /// or nil if the mod was never installed via a Nexus-sourced flow. The
    /// checker uses this to avoid permanently re-flagging mods whose manifest
    /// Version is stale (author forgot to bump) — without modifying the
    /// manifest.json on disk.
    func installedModNexusVersion(for folderName: String) -> String? {
        loadInstalledModRegistry()[folderName]?.nexusVersion
    }

    /// Records the Nexus version known at install time for a mod whose
    /// manifest Version may be stale. The version is stored in the registry
    /// (NOT written to the manifest), so the checker can compare against it
    /// instead of the manifest's value.
    func recordInstalledModNexusVersion(folderName: String, nexusVersion: String) {
        var registry = loadInstalledModRegistry()
        // Create the entry if it doesn't exist yet — `syncInstalledModRegistry`
        // runs at the end of every scan so the entry would normally already
        // be there, but this guard makes the function safe to call between
        // scans (e.g. right after an install, before the first refresh).
        var existing = registry[folderName] ?? InstalledModRecord(
            version: "",
            installedAt: Date(),
            nexusVersion: nil
        )
        existing.nexusVersion = nexusVersion
        registry[folderName] = existing
        saveInstalledModRegistry(registry)
    }

    /// Reconciles the persistent install registry with the mods found on disk
    /// during a scan. Called at the end of every `scanMods()` so that mods
    /// added by ANY means (app installer, drag-and-drop, manual copy into
    /// Mods/ or Mods_disabled/) are tracked.
    ///
    /// - A mod whose version differs from the registry (new install or update)
    ///   is recorded with `Date()` — the actual moment it was detected.
    /// - A mod on disk but absent from the registry (first time seen by the
    ///   app, e.g. manually copied) is recorded with its folder mtime as a
    ///   best-effort timestamp.
    /// - Registry entries for folders no longer on disk are pruned.
    /// One-shot migration flag. When false (first launch with the registry
    /// feature, or an upgrade from a version that used stale folder mtimes),
    /// the registry is wiped and rebuilt from scratch so every entry gets a
    /// clean `Date()` instead of the unreliable archive packaging date.
    private static let registryMigrationV2Key = "registryMigrationV2Done"

    private func syncInstalledModRegistry(scannedMods: [ModItem]) {
        // Flatten groups into individual mods so pack children are tracked too.
        let allMods = scannedMods.flatMap { mod -> [ModItem] in
            mod.isGroup ? (mod.children ?? []) : [mod]
        }

        // Snapshot of the Nexus "extras" cache (version + upload date for
        // every mod id we've ever queried). Used to populate `nexusVersion`
        // for every mod that declares a Nexus id — regardless of HOW it was
        // installed (Nexus in-app download, nxm:// deep link, drag-and-drop,
        // or manual folder copy). Without this, only the in-app Nexus flow
        // (`reconcileManifestVersion`) populated `nexusVersion`, so mods
        // whose author forgot to bump the manifest Version were permanently
        // re-flagged as updatable when installed by any other path.
        let extrasSnapshot = nexusModExtras

        // One-shot migration: wipe any pre-existing registry that was built
        // with stale folder mtimes (from the v1 implementation or from mods
        // registered before the Date()-always fix). This forces every entry
        // to be re-registered with a clean Date(), eliminating the false
        // "same-version update available" flags. Runs exactly once.
        let migrationDone = UserDefaults.standard.bool(forKey: Self.registryMigrationV2Key)
        var registry: [String: InstalledModRecord]
        if !migrationDone {
            registry = [:]
            UserDefaults.standard.set(true, forKey: Self.registryMigrationV2Key)
        } else {
            registry = loadInstalledModRegistry()
        }

        let wasEmpty = registry.isEmpty
        var seenFolders = Set<String>()
        // Dirty flag: only persist if something actually changed. A no-op
        // refresh (no install, no delete, no version bump) is extremely
        // common and skipping the JSON encode + double UserDefaults write
        // is a meaningful saving on every scan.
        var didChange = false

        for mod in allMods {
            let key = mod.folderName
            seenFolders.insert(key)

            // Resolve the Nexus version for this mod from the extras cache.
            // Empty/whitespace-only values are normalized to nil so we don't
            // store a sentinel that the comparator would have to special-case.
            // `nexusModId` is the manifest's `nexus:<id>` (or a user override
            // stored elsewhere); both route through the same `extrasSnapshot`
            // keyed by Nexus mod id.
            let nexusId = effectiveNexusModId(for: mod)
            let knownNexusVersion = (nexusId.isEmpty ? nil
                : extrasSnapshot[nexusId]?.version)?.flatMap { v in
                    v.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? nil : v
                }

            if let existing = registry[key] {
                // Version changed since last scan → this is an update; stamp
                // NOW. Crucially, carry over (or refresh) `nexusVersion` so a
                // re-install doesn't drop the previously reconciled value and
                // re-introduce a false-positive update flag.
                if existing.version != mod.version {
                    registry[key] = InstalledModRecord(
                        version: mod.version,
                        installedAt: Date(),
                        nexusVersion: knownNexusVersion ?? existing.nexusVersion
                    )
                    didChange = true
                } else {
                    // Same version → refresh `nexusVersion` if we just learned
                    // one (e.g. first Nexus check after a manual install) but
                    // leave version/installedAt untouched.
                    if let nv = knownNexusVersion, nv != existing.nexusVersion {
                        registry[key] = InstalledModRecord(
                            version: existing.version,
                            installedAt: existing.installedAt,
                            nexusVersion: nv
                        )
                        didChange = true
                    }
                }
            } else {
                // New mod (not in registry): always record with NOW. We
                // intentionally do NOT use the folder mtime — `copyItem`
                // preserves the archive's packaging date, which is always
                // older than the Nexus upload and would trigger a spurious
                // same-version update flag. A mod detected on disk for the
                // first time was installed recently (this session or a prior
                // one), so NOW is the most accurate available timestamp.
                registry[key] = InstalledModRecord(
                    version: mod.version,
                    installedAt: Date(),
                    nexusVersion: knownNexusVersion
                )
                didChange = true
            }
        }

        // Prune registry entries for folders that no longer exist on disk.
        let beforePruneCount = registry.count
        registry = registry.filter { seenFolders.contains($0.key) }
        if registry.count != beforePruneCount {
            didChange = true
        }

        if didChange {
            saveInstalledModRegistry(registry)
        }

        // If the registry was empty (first launch, cleared, corrupt, or just
        // migrated) and we just populated it, log the rebuild.
        if wasEmpty && !registry.isEmpty {
            self.log(
                String(format: "Install registry rebuilt: %d mod(s) registered from disk.",
                       registry.count),
                level: .info
            )
        }
    }

